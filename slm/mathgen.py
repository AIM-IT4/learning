def C(expr):
    """A calculator note and its result: C('7*12') -> ('<<7*12=84>>84', '84')."""
    r = fmt(evaluate(expr))
    return f"<<{expr}={r}>>{r}", r


def lower_first(s):
    return s[0].lower() + s[1:]


