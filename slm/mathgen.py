SUBJECT = {f.__name__: s for s, fs in [
    ("maths", FAMILIES[:14]), ("physics", FAMILIES[14:20]), ("finance", FAMILIES[20:24]), ("statistics", FAMILIES[24:])]
    for f in fs}


def problem(R, split="train", family=None):
    """One problem. split='train' uses wordings 0-3; split='heldout' uses wording 4 only."""
    f = family or R.choice(FAMILIES)
    t = R.randrange(TRAIN_WORDINGS) if split == "train" else HELDOUT_WORDING
    q, lines, ans = f(R, t)
    return {"family": f.__name__, "subject": SUBJECT[f.__name__], "question": q,
            "solution": "\n".join(lines) + f"\n#### {ans}", "answer": ans}


def to_text(p):
    """The exact text the model trains on."""
    return f"Q: {p['question']}\nA: {p['solution']}"


NOTE = re.compile(r"<<([^=<>]+)=([^<>]+)>>")


def check(samples=300):
    """Every calculator note must be correct and every answer must be a number."""
    R = random.Random(1)
    bad = 0
    for f in FAMILIES:
        for t in range(HELDOUT_WORDING + 1):
            for _ in range(samples):
                q, lines, ans = f(R, t)
                text = "\n".join(lines)
                for expr, res in NOTE.findall(text):
                    if fmt(evaluate(expr)) != res:
                        bad += 1
                float(ans)
                assert "{" not in q and "}" not in q, q
    print(f"checked {len(FAMILIES)} families x {HELDOUT_WORDING + 1} wordings x {samples}: {bad} wrong notes")
    return bad == 0


