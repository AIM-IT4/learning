"""Our training data: maths, physics, finance and statistics word problems with
step-by-step solutions, all generated by code.

Solutions use calculator notes, as in the GSM8K dataset: `7 * 12 = <<7*12=84>>84`.
When the model writes `<<7*12=`, solve.py runs the calculation and writes `84>>84` for
it. The model learns the reasoning; the calculator does the arithmetic.

Every family has 5 wordings. Wordings 0-3 are for training; wording 4 is never trained
on, so it tests whether the model understands new phrasing.

    python mathgen.py            # print a few examples
    python mathgen.py --check    # verify every family and wording
"""
